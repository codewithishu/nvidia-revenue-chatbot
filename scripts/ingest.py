"""Parse PDFs in data/raw -> chunks -> embeddings -> index/. Also writes a coverage report."""
from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from nvrag.chunking import make_chunks  # noqa: E402
from nvrag.config import load_config  # noqa: E402
from nvrag.docmeta import infer_meta, load_manifest  # noqa: E402
from nvrag.indexer import Embedder, save_index  # noqa: E402
from nvrag.parsing import parse_pdf  # noqa: E402

YEARS = range(1998, 2027)


def write_coverage(rows: list[dict], out_dir: Path) -> None:
    by = defaultdict(set)
    for r in rows:
        if r["year"]:
            by[r["doc_type"]].add(r["year"])
    lines = ["# Coverage report (auto-generated by scripts/ingest.py)", ""]
    lines += ["| file | type | year | year source | pages | text chunks | table chunks | empty pages | OCR pages |",
              "|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (r["doc_type"], r["year"] or 0)):
        lines.append(
            f"| {r['file']} | {r['doc_type']} | {r['year']} | {r['year_source']} | {r['pages']} | "
            f"{r['text_chunks']} | {r['table_chunks']} | {r['empty_pages']} | {r['ocr_pages']} |"
        )
    lines += ["", "## Missing years (1998-2026)"]
    for t in ("annual_report", "proxy"):
        missing = [y for y in YEARS if y not in by[t]]
        lines.append(f"- **{t}**: {', '.join(map(str, missing)) if missing else 'none'}")
    flagged = [r["file"] for r in rows if r["empty_pages"] > 0.3 * max(r["pages"], 1)]
    if flagged:
        lines += ["", "## Likely scanned (many pages without text) - re-run with OCR=1", *[f"- {f}" for f in flagged]]
    unk = [r["file"] for r in rows if r["doc_type"] == "unknown" or not r["year"]]
    if unk:
        lines += ["", "## Could not infer type/year - add them to data/manifest.csv", *[f"- {f}" for f in unk]]
    out_dir.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines) + "\n"
    (out_dir / "COVERAGE.md").write_text(text)
    Path("docs").mkdir(exist_ok=True)
    Path("docs/COVERAGE.md").write_text(text)
    print("\n" + text)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", type=Path)
    ap.add_argument("--index-dir", type=Path)
    ap.add_argument("--ocr", action="store_true", help="OCR pages without a text layer (needs Tesseract)")
    args = ap.parse_args()

    cfg = load_config()
    data_dir = args.data_dir or cfg.data_dir
    index_dir = args.index_dir or cfg.index_dir
    ocr = args.ocr or cfg.ocr

    pdfs = sorted(data_dir.glob("*.pdf"))
    if not pdfs:
        sys.exit(f"No PDFs found in {data_dir}. See README 'Getting the data'.")
    manifest = load_manifest(cfg.manifest_path)

    all_chunks, rows = [], []
    for p in pdfs:
        print(f"Parsing {p.name} ...")
        try:
            pages = parse_pdf(p, ocr=ocr)
        except Exception as e:  # corrupt / encrypted file should not kill the whole run
            print(f"  !! failed: {e}")
            continue
        first_text = " ".join(" ".join(pc.blocks) for pc in pages[:3])
        meta = infer_meta(p, first_text, manifest)
        if meta.doc_type == "skip":
                 print("  skipped (not an annual report or proxy)")
                 continue
        chunks = make_chunks(meta, pages, cfg)
        empty = sum(1 for pc in pages if not pc.blocks and not pc.tables)
        rows.append({
            "file": p.name, "doc_type": meta.doc_type, "year": meta.year, "year_source": meta.year_source,
            "pages": len(pages), "text_chunks": sum(c.kind == "text" for c in chunks),
            "table_chunks": sum(c.kind == "table" for c in chunks), "empty_pages": empty,
            "ocr_pages": sum(pc.ocr for pc in pages),
        })
        print(f"  {meta.doc_type} {meta.year} ({meta.year_source}): {len(pages)} pages, {len(chunks)} chunks")
        all_chunks.extend(chunks)

    if not all_chunks:
        sys.exit("No chunks produced - are the PDFs image-only? Try --ocr.")
    print(f"\nEmbedding {len(all_chunks)} chunks with {cfg.embed_model} ...")
    emb = Embedder(cfg.embed_model).encode_docs([c.embed_text() for c in all_chunks])
    info = {"embed_model": cfg.embed_model, "n_chunks": len(all_chunks), "documents": rows}
    save_index(index_dir, all_chunks, emb, info)
    write_coverage(rows, index_dir)
    print(f"Index written to {index_dir}/")


if __name__ == "__main__":
    main()
